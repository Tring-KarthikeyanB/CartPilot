import com.cartpilot.data.model.ReceiptDto
import com.cartpilot.data.remote.NetworkModule
import com.cartpilot.data.repository.toDomain
import com.cartpilot.domain.model.StockStatus
import kotlinx.serialization.json.JsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Decodes real backend responses (generated by backend/scripts/export_api_fixtures.py) with the app's
 * DTOs and JSON configuration, so any drift between the FastAPI schemas and the Android models fails here.
 */
class ApiContractTest {
    private val json = NetworkModule.json

    private fun fixture(name: String): String =
        requireNotNull(javaClass.classLoader?.getResource("fixtures/$name.json")) { "missing fixture $name" }.readText()

    private inline fun <reified T> decode(name: String): T = json.decodeFromString(fixture(name))

    @Test
    fun health() {
        val dto = decode<HealthDto>("health")
        assertEquals("ok", dto.status)
        assertTrue(dto.checks.geminiConfigured)
    }

    @Test
    fun productsAndCategories() {
        val products = decode<ProductListDto>("products").items.map { it.toDomain() }
        assertTrue(products.isNotEmpty() && products.all { it.category == "headphones" })
        assertTrue(products.first().imageUrl.startsWith("http://10.0.2.2:8000/static/products/"))
        assertEquals(7, decode<List<CategoryDto>>("categories").size)
    }

    @Test
    fun comparison() {
        val c = decode<ComparisonDto>("compare").toDomain()
        assertEquals(3, c.products.size)
        assertEquals("kb-005", c.cheapestId)
        assertTrue(c.summary.isNotBlank())
    }

    @Test
    fun chatTurn() {
        val turn = decode<ChatResponseDto>("chat").toDomain()
        assertEquals(listOf("hp-003", "kb-005"), turn.products.map { it.id })
        assertTrue(turn.cartUpdated)
        assertEquals(229.98, turn.cart.subtotal, 0.001)
        assertEquals(500.0, turn.cart.budget!!, 0.001)
        assertTrue(turn.actions.any { it.tool == "add_to_cart" && it.ok })
        assertNotNull(turn.budget)
    }

    @Test
    fun cartAndBudget() {
        val cart = decode<CartDto>("cart").toDomain()
        assertTrue(cart.overBudget)
        assertEquals(-29.98, cart.budgetRemaining!!, 0.001)
        assertEquals(StockStatus.InStock, cart.items.first().stock)
        val check = decode<BudgetCheckDto>("budget_check").toDomain()
        assertTrue(!check.withinBudget && check.suggestions.isNotEmpty())
    }

    @Test
    fun paymentFlow() {
        val order = decode<CreateOrderResponseDto>("create_order").toDomain()
        assertTrue(order.approveUrl.startsWith("https://www.sandbox.paypal.com/"))
        assertEquals(229.98, order.amount, 0.001)

        val pending = decode<OrderStatusDto>("order_status_pending").toDomain()
        assertTrue(!pending.isCompleted && !pending.canCapture)
        assertNull(pending.receipt)

        val receipt = decode<ReceiptDto>("receipt").toDomain()
        assertEquals(order.orderId, receipt.orderId)
        assertEquals("COMPLETED", receipt.paypalStatus)
        assertTrue(receipt.captureId.isNotBlank())

        val done = decode<OrderStatusDto>("order_status_completed").toDomain()
        assertTrue(done.isCompleted)
    }

    @Test
    fun errorEnvelopes() {
        val notFound = decode<ErrorEnvelopeDto>("error_not_found").error
        assertEquals("product_not_found", notFound.code)

        val validation = decode<ErrorEnvelopeDto>("error_validation").error
        assertEquals("invalid_request", validation.code)
        assertNull(validation.detailsObject) // details is a list for validation errors

        val changed = decode<ErrorEnvelopeDto>("error_cart_changed").error
        assertEquals("cart_changed", changed.code)
        assertEquals(229.98, (changed.detailsObject!!["current_total"] as JsonPrimitive).content.toDouble(), 0.001)

        val notApproved = decode<ErrorEnvelopeDto>("error_not_approved").error
        assertEquals("payment_not_approved", notApproved.code)
        assertTrue((notApproved.detailsObject!!["approve_url"] as JsonPrimitive).content.startsWith("https://"))
    }
}
